"""Generate soong-prune.mk: PRODUCT_SOURCE_ROOT_DIRS entries that keep Soong
from parsing trees this device never builds from, without pruning anything a
kept module still references.

Usage (inside the build container, after one analysis wrote the file list):
  soong-prune.py <out/.module_paths/Android.bp.list> <src root> \
      <candidate prefix>... -- <fixed prefix>... > soong-prune.mk

Candidates are split, directory by directory, until no kept Android.bp names a
module defined under a pruned prefix. Fixed prefixes are pruned whole; use
them for trees a real Soong run already accepted pruning but that this
string-based check over-keeps (Soong namespaces it cannot see).

Known limits, each found the hard way:
  * References are matched as quoted strings (bare, ":name", "//dir:name",
    ":name{.tag}"); module-type-generated dependencies are invisible, so a
    kept Android.bp keeps its whole subtree.
  * A namespace-declaring Android.bp is never pruned on its own: its kept
    children would fall into the global namespace and collide.
  * Blueprint matches prefixes as plain strings, so directories get a
    trailing slash ("-cts/hostsidetests/input" also prunes ".../inputmethod").
"""
import os
import re
import sys

NAME = re.compile(r'^\s*name:\s*"([^"]+)"', re.M)
# A quoted module name, bare or as a source reference: ":name", "//dir:name",
# optionally with an output tag (":name{.tag}").
QUOTED = re.compile(r'"(?://[^":]*:|:)?([A-Za-z0-9_.@+\-]+)(?:\{[^"]*\})?"')

bp_list, root = sys.argv[1], sys.argv[2]
# Prefixes after "--" are fixed: pruned, already proven clean by a real Soong
# run, and never split. The ones before it are candidates to refine.
rest = sys.argv[3:]
if "--" in rest:
    k = rest.index("--")
    prefixes, fixed = rest[:k], rest[k + 1:]
else:
    prefixes, fixed = rest, []
files = [l.strip() for l in open(bp_list) if l.strip()]
text = {}
for f in files:
    try:
        text[f] = open(os.path.join(root, f), errors="replace").read()
    except OSError:
        text[f] = ""


def under(f, p):
    return f == p or f.startswith(p + "/")


def defined(fs):
    out = {}
    for f in fs:
        for n in NAME.findall(text[f]):
            out.setdefault(n, f)
    return out


def children(p):
    return sorted({p + "/" + f[len(p) + 1:].split("/")[0]
                   for f in files if f.startswith(p + "/") and "/" in f[len(p) + 1:]})


def split(p, bad):
    """Prefixes covering p's subtree minus every file in bad (p's own top-level
    Android.bp is kept whenever p has to be split)."""
    if not any(under(b, p) for b in bad):
        return [p]
    # A kept Android.bp keeps its whole subtree: module types add implicit
    # dependencies into their own subdirectories (a tradefed suite pulls in
    # "<name>-tradefed-tests" from tests/), which no string match can see.
    if p + "/Android.bp" in bad:
        return []
    out = []
    # Split: p's own Android.bp is pruned on its own (prefixes match as plain
    # strings, so "p/Android.bp" covers exactly that file); if anything uses
    # its modules, the next round finds it in bad and keeps p whole.
    # Never alone when it declares a soong_namespace: its kept children would
    # fall into the global namespace and collide with same-named modules.
    own = p + "/Android.bp"
    if own in text and "soong_namespace" not in text[own]:
        out.append(own)
    for c in children(p):
        out.extend(split(c, bad))
    return out


def refine(prefixes):
    while True:
        pset = prefixes + fixed
        pruned = [f for f in files if any(under(f, p) for p in pset)]
        pruned_set = set(pruned)
        names = defined(pruned)
        used = set()
        for f in files:
            if f in pruned_set:
                continue
            used.update(n for n in QUOTED.findall(text[f]) if n in names)
        if not used:
            return prefixes
        bad = {names[n] for n in used}
        for b in sorted(bad):
            print(f"keep {b}: {sorted(n for n in used if names[n] == b)[:3]}", file=sys.stderr)
        new = []
        stuck = [b for b in bad if any(under(b, p) for p in fixed)]
        if stuck:
            print(f"WARNING: fixed prefixes define referenced files: {sorted(stuck)[:5]}", file=sys.stderr)
            bad -= set(stuck)
            if not bad:
                return prefixes
        for p in prefixes:
            new.extend(split(p, bad))
        prefixes = sorted(set(new))


final = refine(prefixes)
pruned = sum(1 for f in files if any(under(f, p) for p in final + fixed))
print(f"{len(final) + len(fixed)} prefixes prune {pruned} of {len(files)} Android.bp files", file=sys.stderr)

entries = [p if p.endswith(".bp") else p + "/" for p in final + fixed]
print("# Generated by build/soong-prune.py; do not edit.")
print("PRODUCT_SOURCE_ROOT_DIRS += \\")
for i, e in enumerate(entries):
    print(f"    -{e}" + (" \\" if i < len(entries) - 1 else ""))

#!/system/bin/sh
# Runs ON THE PHONE as root. Writes selected partitions back from images
# staged in $SRC, after checking each against the dump manifest.
#
# For the per-device partitions fastboot won't take (nvram, nvdata, persist,
# proinfo, ...) and the preloader LUNs. Use only for a partition that is
# actually damaged or was erased (a Motorola rescue flash erases nvdata).
#
#   adb push <img> ... SHA256SUMS device-restore.sh /data/local/tmp/rs/
#   adb shell su -c 'sh /data/local/tmp/rs/device-restore.sh nvdata'           # dry run
#   adb shell su -c 'GO=1 sh /data/local/tmp/rs/device-restore.sh nvdata'      # write
#
# Mounted partitions (nvdata, nvcfg, persist, prodpersist, protect1/2,
# metadata) are frozen before the write and the script then hard-reboots
# without sync: a clean unmount would flush the kernel's old view of the
# filesystem back over the restored image.

BB=/data/adb/magisk/busybox
SRC=${SRC:-/data/local/tmp/rs}
BYNAME=/dev/block/by-name

# Never written from here: userdata is not in the backup; seccfg encodes the
# bootloader lock state and is regenerated by fastboot oem lock/unlock; efuse
# is a mirror of one-time-programmable fuses.
REFUSE=" userdata seccfg efuse "

FROZEN=""

# A failure after freezing must not leave the phone with frozen filesystems.
# Thawing lets the old state flush back, so the partial write is reported loudly.
die() {
    echo "FATAL: $*"
    for m in $FROZEN; do
        $BB fsfreeze --unfreeze "$m"
        echo "thawed $m: its partition may hold a partial write, re-run before rebooting"
    done
    exit 1
}

# mountpoint for a block device if it is mounted rw, else empty
rw_mount() {
    while read -r src mnt fs opts rest; do
        [ "$(readlink -f "$src")" = "$1" ] || continue
        case ",$opts," in
            *,rw,*) echo "$mnt"; return ;;
        esac
    done < /proc/mounts
}

[ "$(id -u)" = 0 ] || die "not root"
[ "$(getprop ro.product.device)" = cancunf ] || die "not a cancunf"
[ $# -gt 0 ] || die "name the partitions to restore"
[ -f "$SRC/SHA256SUMS" ] || die "no $SRC/SHA256SUMS"

for name in "$@"; do
    case "$REFUSE" in *" $name "*) die "$name is never restored by this script" ;; esac

    img="$SRC/$name.img"
    dev=$(readlink -f "$BYNAME/$name")
    [ -f "$img" ] || die "missing $img"
    [ -b "$dev" ] || die "no block device for $name"

    want=$(grep "  $name.img\$" "$SRC/SHA256SUMS" | cut -d' ' -f1)
    got=$($BB sha256sum "$img" | cut -d' ' -f1)
    [ -n "$want" ] || die "$name not in manifest"
    [ "$want" = "$got" ] || die "$name image hash $got != manifest $want"

    isz=$($BB stat -c %s "$img")
    dsz=$($BB blockdev --getsize64 "$dev")
    [ "$isz" = "$dsz" ] || die "$name image $isz bytes != partition $dsz bytes"

    mnt=$(rw_mount "$dev")

    if [ "$GO" != 1 ]; then
        echo "would write $name ($isz bytes) -> $dev ${mnt:+[mounted at $mnt: freeze + hard reboot]}"
        continue
    fi

    if [ -n "$mnt" ]; then
        sync
        $BB fsfreeze --freeze "$mnt" || die "freeze $mnt"
        FROZEN="$FROZEN $mnt"
    fi

    $BB dd if="$img" of="$dev" bs=4194304 conv=fsync 2>/dev/null || die "dd $name"
    back=$($BB dd if="$dev" bs=4194304 2>/dev/null | $BB sha256sum | cut -d' ' -f1)
    [ "$back" = "$want" ] || die "$name readback $back != $want"
    echo "restored $name -> $dev (readback verified)"
done

if [ "$GO" != 1 ]; then
    echo "dry run; set GO=1 to write"
    exit 0
fi

if [ -n "$FROZEN" ]; then
    echo "frozen:$FROZEN -> hard reboot without sync"
    $BB reboot -f
fi
